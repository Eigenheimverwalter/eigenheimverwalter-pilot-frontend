import fs from 'node:fs';
import path from 'node:path';
import {toBookablePostalEntry} from './postal-catalog-policy.mjs';

const [input='/.tmp/missing-DE.txt',catalogOutput='data/geonames-de-postal-codes.json',migrationOutput='supabase/migrations/202609140002_geonames_de_postal_catalog.sql',runtimeFile='data/runtime.json']=process.argv.slice(2);
const sourceVersion=process.env.GEONAMES_SOURCE_VERSION||new Date().toISOString().slice(0,10);
const stateAliases=new Map(Object.entries({
  Bavaria:'Bayern','Land Berlin':'Berlin','Lower Saxony':'Niedersachsen',
  'Mecklenburg-Western Pomerania':'Mecklenburg-Vorpommern',Saxony:'Sachsen',
  'Saxony-Anhalt':'Sachsen-Anhalt',Thuringia:'Thüringen'
}));
const expectedStates=new Set(['Baden-Württemberg','Bayern','Berlin','Brandenburg','Bremen','Hamburg','Hessen','Mecklenburg-Vorpommern','Niedersachsen','Nordrhein-Westfalen','Rheinland-Pfalz','Saarland','Sachsen','Sachsen-Anhalt','Schleswig-Holstein','Thüringen']);
const records=new Map();
for(const line of fs.readFileSync(input,'utf8').split(/\r?\n/)){
  if(!line)continue;
  const [country,postalCode,place,rawState,,admin2Name,,admin3Name,,latitude,longitude]=line.split('\t');
  const state=stateAliases.get(rawState)||rawState;
  if(country!=='DE'||!/^[0-9]{5}$/.test(postalCode)||!expectedStates.has(state))continue;
  const current=records.get(postalCode)||{postalCode,city:place,state,latitude:Number(latitude),longitude:Number(longitude),placeNames:[],districts:[]};
  if(place&&!current.placeNames.includes(place))current.placeNames.push(place);
  for(const district of [admin2Name,admin3Name])if(district&&!current.districts.includes(district))current.districts.push(district);
  records.set(postalCode,current);
}
const catalog=[...records.values()].map(toBookablePostalEntry).filter(Boolean).sort((a,b)=>a.postalCode.localeCompare(b.postalCode,'de'));
const states=new Set(catalog.map(item=>item.state));
const invalid=catalog.filter(item=>!/^[0-9]{5}$/.test(item.postalCode)||!Number.isFinite(item.latitude)||!Number.isFinite(item.longitude));
if(catalog.length<7000||states.size!==16||invalid.length||new Set(catalog.map(item=>item.postalCode)).size!==catalog.length)throw new Error(`GeoNames-Integritätsprüfung fehlgeschlagen: ${catalog.length} PLZ, ${states.size} Bundesländer, ${invalid.length} ungültig`);
const metadata={source:'GeoNames',country:'DE',sourceUrl:'https://download.geonames.org/export/zip/DE.zip',license:'CC BY 4.0',sourceVersion,postalCodeCount:catalog.length,stateCount:states.size,importedAt:new Date().toISOString(),excludedWithoutGermanState:true,excludedInstitutionalRecipients:true,catalogPurpose:'bookable-locality-postal-codes'};
const payload={metadata,entries:catalog};
fs.mkdirSync(path.dirname(catalogOutput),{recursive:true});
fs.writeFileSync(catalogOutput,JSON.stringify(payload,null,2)+'\n');
const sqlJson=JSON.stringify(payload).replaceAll('$geonames$','$geo_names$');
const sql=`-- Generated by scripts/import-geonames-postal-codes.mjs from GeoNames DE.zip (CC BY 4.0).\n`+
`do $$\ndeclare catalog jsonb := $geonames$${sqlJson}$geonames$::jsonb;\nbegin\n`+
`  if jsonb_array_length(catalog->'entries') < 7000 then raise exception 'POSTAL_CATALOG_INCOMPLETE'; end if;\n`+
`  update public.portal_runtime_state\n  set payload=jsonb_set(jsonb_set(payload,'{postalDirectory}',catalog->'entries',true),'{postalCatalogMeta}',catalog->'metadata',true),\n      revision=revision+1,updated_at=now()\n  where id='primary';\n`+
`  if not found then raise exception 'PORTAL_RUNTIME_STATE_MISSING'; end if;\nend $$;\n`;
fs.mkdirSync(path.dirname(migrationOutput),{recursive:true});
fs.writeFileSync(migrationOutput,sql);
if(runtimeFile&&fs.existsSync(runtimeFile)){
  const runtime=JSON.parse(fs.readFileSync(runtimeFile,'utf8'));
  runtime.postalDirectory=catalog;
  runtime.postalCatalogMeta=metadata;
  fs.writeFileSync(runtimeFile,JSON.stringify(runtime,null,2)+'\n');
}
console.log(JSON.stringify({status:'generated',...metadata}));
